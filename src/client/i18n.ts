/** `{name}` 占位符插值；词表里没有的 key 原样回显（与 `ctx.locale.bind` 的行为一致）。 */
export function text(t: TFn, key: string, params?: Record<string, string | number>): string {
	let value = t(key);
	if (params) {
		for (const name of Object.keys(params)) value = value.split(`{${name}}`).join(String(params[name]));
	}
	return value;
}

